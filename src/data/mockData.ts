// Helper to generate additional realistic complaints up to 120 total
function generateComprehensiveComplaints(): Complaint[] {
  const result: Complaint[] = [...MOCK_COMPLAINTS];
  const categories = [
    "Fee Overcharging & Capitation Fees",
    "Faculty Non-payment & Ghost Faculty",
    "Infrastructure Deficiencies & Safety",
    "Unapproved Program Intake",
    "Withholding Original Marksheets / TC",
    "Denial of AICTE Tuition Fee Waiver (TFW)",
    "Hostel & Canteen Facility Grievance",
    "Examination Malpractice & Irregularity",
  ];
  
  const statuses: Complaint["currentStatus"][] = [
    "UNDER_PROCESS",
    "PENDING_INQUIRY",
    "RECEIVED",
    "DISPOSED",
    "UNDER_PROCESS",
    "DISPOSED",
  ];

  const priorities: Complaint["priority"][] = ["MEDIUM", "LOW", "HIGH", "MEDIUM"];
  const complainants: Complaint["complainantType"][] = ["Student", "Parent", "Faculty Member", "Whistleblower", "Citizen"];

  let compCounter = 850;
  for (let i = 0; i < MOCK_INSTITUTIONS.length; i++) {
    const inst = MOCK_INSTITUTIONS[i];
    const complaintsToAdd = 4 + (i % 4); // 4 to 7 complaints per institution
    
    for (let c = 0; c < complaintsToAdd; c++) {
      compCounter++;
      const id = `COMP-2026-0${compCounter}`;
      const officer = MOCK_OFFICERS[c % MOCK_OFFICERS.length];
      const category = categories[(i + c) % categories.length];
      const status = statuses[(i * 3 + c) % statuses.length];
      const priority = priorities[(c + i) % priorities.length];
      const complainant = complainants[(i + c) % complainants.length];
      
      const dayReceived = 1 + ((i * 3 + c * 5) % 28);
      const month = c % 2 === 0 ? "01" : "02";
      const dateReceived = `2026-${month}-${String(dayReceived).padStart(2, "0")}`;
      const expectedDisposalDate = `2026-03-${String(Math.min(28, dayReceived + 15)).padStart(2, "0")}`;
      
      let sla: Complaint["slaCondition"] = "ON_TRACK";
      if (status === "DISPOSED") {
        sla = "ON_TRACK";
      } else if (c % 5 === 0) {
        sla = "OVERDUE";
      } else if (c % 3 === 0) {
        sla = "NEARING_DEADLINE";
      }

      result.push({
        id,
        institutionId: inst.id,
        institutionName: inst.name,
        institutionPermanentId: inst.permanentId,
        category,
        bureau: officer.bureau,
        assignedOfficer: officer,
        currentStatus: status,
        priority,
        dateReceived,
        expectedDisposalDate,
        slaCondition: sla,
        subject: `${category} reported regarding ${inst.shortName}`,
        description: `Formal representation submitted concerning ${category.toLowerCase()} at ${inst.name}. Matter requires examination under standard AICTE regulations.`,
        complainantType: complainant,
        lastAction: status === "DISPOSED" ? "Final disposal order passed; compliance noted" : "Internal scrutiny report prepared",
        lastActionDate: "2026-02-26",
        nextRequiredAction: status === "DISPOSED" ? "None (Case Closed)" : "Seek rejoinder from institution",
        relatedCaseIds: [],
        supportingDocuments: [
          { name: `Supporting_Doc_${compCounter}.pdf`, size: "1.1 MB", dateUploaded: dateReceived, type: "application/pdf" }
        ],
        actionHistory: [
          { id: `ACT-GEN-${compCounter}`, date: dateReceived, action: "Receipt Acknowledged", officer: officer.name, bureau: officer.bureau, remarks: "Scrutiny commenced" }
        ]
      });
    }
  }

  return result;
}

